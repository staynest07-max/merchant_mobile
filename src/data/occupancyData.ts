const MS_PER_DAY = 24 * 60 * 60 * 1000;
const today = new Date();

function isoDaysFromNow(days: number): string {
  const d = new Date(today);
  d.setDate(d.getDate() + days);
  return d.toISOString().split('T')[0];
}

